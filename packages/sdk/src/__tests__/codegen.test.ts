import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { parseAbiType, parseSorobanSpec, validateAbi } from "../abi.js";
import type { ContractAbi } from "../abi.js";
import { generateClient, generateClients, SUPPORTED_LANGUAGES } from "../codegen.js";
import { AccordValidationError } from "../errors.js";
import * as sdk from "../index.js";

const specJson = readFileSync(new URL("./fixtures/accord-spec.json", import.meta.url), "utf8");

describe("ABI parsing", () => {
  it("normalizes a Soroban spec into functions and types, skipping events", () => {
    const abi = parseSorobanSpec(specJson);
    expect(abi.functions.map((f) => f.name)).toEqual([
      "get_threshold",
      "get_owners",
      "get_proposal",
      "get_spending_limit",
      "approve",
      "create_proposal",
    ]);
    expect(abi.types.map((t) => `${t.kind}:${t.name}`)).toEqual([
      "struct:Transfer",
      "union:ProposalStatus",
      "union:ProposalCategory",
      "union:ProposalKind",
      "struct:Proposal",
      "errorEnum:ContractError",
    ]);
    expect(abi.functions[3].doc).toContain("\nlimit is set.");
  });

  it("parses nested compound types", () => {
    expect(parseAbiType({ map: { key_type: "address", value_type: { vec: { element_type: "i128" } } } })).toEqual({
      kind: "map",
      key: { kind: "primitive", name: "address" },
      value: { kind: "vec", element: { kind: "primitive", name: "i128" } },
    });
    expect(parseAbiType({ tuple: { value_types: ["u32", { bytes_n: { n: 32 } }] } })).toEqual({
      kind: "tuple",
      elements: [{ kind: "primitive", name: "u32" }, { kind: "bytesN", size: 32 }],
    });
  });

  it("rejects malformed specs with a field path", () => {
    expect(() => parseSorobanSpec("{not json")).toThrow(AccordValidationError);
    expect(() => parseSorobanSpec({})).toThrow(/Expected an array/);
    expect(() => parseAbiType("u7", "x")).toThrow(/Unknown primitive type 'u7'/);
    expect(() => parseAbiType({ bytes_n: { n: 0 } })).toThrow(/positive integer/);
    expect(() =>
      parseSorobanSpec([{ function_v0: { name: "bad-name", inputs: [], outputs: [] } }])
    ).toThrow(/spec\[0\]\.function_v0\.name/);
  });

  it("rejects undeclared type references and duplicates", () => {
    expect(() =>
      parseSorobanSpec([{ function_v0: { name: "f", inputs: [], outputs: [{ udt: { name: "Missing" } }] } }])
    ).toThrow(/'Missing' is referenced but never declared/);

    const dup: ContractAbi = {
      functions: [
        { name: "f", doc: "", inputs: [], outputs: [] },
        { name: "f", doc: "", inputs: [], outputs: [] },
      ],
      types: [],
    };
    expect(() => validateAbi(dup)).toThrow(/Duplicate function 'f'/);
  });
});

describe("Python client generation", () => {
  const { fileName, source } = generateClient(parseSorobanSpec(specJson), { language: "python" });

  it("emits typed dataclasses, enums, unions and client methods", () => {
    expect(fileName).toBe("accord_contract_client.py");
    expect(source).toMatch(/^# Code generated by @accord-protocol\/sdk codegen\. DO NOT EDIT\./);
    expect(source).toContain("@dataclass\nclass Proposal:\n    \"\"\"A treasury proposal.\"\"\"\n    id: int\n");
    expect(source).toContain("    attachment_hash: Optional[bytes]");
    expect(source).toContain("class ContractError(IntEnum):\n    AlreadyInitialized = 1");
    expect(source).toContain('    TAGS: ClassVar[Tuple[str, ...]] = ("Transfer", "AddOwner")');
    expect(source).toContain(
      "    def get_proposal(self, proposal_id: int) -> Proposal:\n" +
        '        return self._invoker.invoke("get_proposal", [("proposal_id", proposal_id)])'
    );
    expect(source).toContain("    def get_spending_limit(self, owner: str, token: str) -> Optional[int]:");
    expect(source).toContain(
      '    def approve(self, approver: str, proposal_id: int) -> None:\n        self._invoker.invoke("approve"'
    );
    expect(source).toContain("transfers: List[Transfer]");
  });

  it("escapes reserved words", () => {
    const abi: ContractAbi = {
      functions: [{ name: "from", doc: "", inputs: [{ name: "lambda", doc: "", type: { kind: "primitive", name: "u32" } }], outputs: [] }],
      types: [],
    };
    const { source: py } = generateClient(abi, { language: "python" });
    expect(py).toContain('def from_(self, lambda_: int) -> None:\n        self._invoker.invoke("from", [("lambda", lambda_)])');
  });
});

describe("Go client generation", () => {
  const { fileName, source } = generateClient(parseSorobanSpec(specJson), {
    language: "go",
    clientName: "Treasury",
    packageName: "treasury",
  });

  it("emits a package with structs, consts, error type and methods", () => {
    expect(fileName).toBe("treasury.go");
    expect(source).toContain("package treasury\n\nimport (\n\t\"fmt\"\n\t\"math/big\"\n)");
    expect(source).toContain("\tAmount *big.Int `json:\"amount\"`");
    expect(source).toContain("\tAttachmentHash *[32]byte        `json:\"attachment_hash\"`");
    expect(source).toContain("\tProposalStatusPending   = \"Pending\"");
    expect(source).toContain("\tContractErrorRecoveryActive     ContractError = 57");
    expect(source).toContain("func (e ContractError) Error() string {");
    expect(source).toContain(
      "func (c *Treasury) GetProposal(proposalId uint64) (Proposal, error) {\n" +
        "\tvar out Proposal\n" +
        '\terr := c.invoker.Invoke("get_proposal", []Arg{{"proposal_id", proposalId}}, &out)\n'
    );
    expect(source).toContain(
      'func (c *Treasury) Approve(approver string, proposalId uint64) error {\n\treturn c.invoker.Invoke("approve"'
    );
    expect(source).toContain("// Returns the spending limit for an (owner, token) pair, or `None` if no\n// limit is set.");
  });

  it("only imports what it uses", () => {
    const abi: ContractAbi = {
      functions: [{ name: "ping", doc: "", inputs: [], outputs: [{ kind: "primitive", name: "u32" }] }],
      types: [],
    };
    const { source: go } = generateClient(abi, { language: "go" });
    expect(go).not.toContain("import");
    expect(go).toContain("func (c *AccordContractClient) Ping() (uint32, error) {");
  });
});

describe("generateClient validation", () => {
  const abi = parseSorobanSpec(specJson);

  it("rejects unsupported languages", () => {
    expect(() => generateClient(abi, { language: "cobol" as never })).toThrow(/Unsupported language 'cobol'/);
  });

  it("rejects invalid or colliding client and package names", () => {
    expect(() => generateClient(abi, { language: "python", clientName: "lower" })).toThrow(AccordValidationError);
    expect(() => generateClient(abi, { language: "python", clientName: "Proposal" })).toThrow(/collides/);
    expect(() => generateClient(abi, { language: "go", packageName: "Bad-Pkg" })).toThrow(/package name/);
  });

  it("generates every supported language and is exported from the package root", () => {
    expect(generateClients(abi).map((c) => c.language)).toEqual([...SUPPORTED_LANGUAGES]);
    expect(sdk.generateClient).toBe(generateClient);
    expect(sdk.parseSorobanSpec).toBe(parseSorobanSpec);
  });
});
